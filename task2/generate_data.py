#!/usr/bin/env python3
r"""Parse task2 bench/*_results.txt and emit task2/report/data.tex with LaTeX macros.

Run from task2/:  python3 generate_data.py
Then compile:     cd report && pdflatex task2_report.tex
"""

import os, re

BASE = os.path.dirname(os.path.abspath(__file__))
OUT  = os.path.join(BASE, 'report', 'data.tex')

def parse_float(s):
    try: return float(s.strip().replace(',', ''))
    except ValueError: return None

def parse_speedup(s):
    s = s.strip().rstrip('x')
    try:
        v = float(s)
        return f'{v:.2f}x' if v > 0 else '--'
    except ValueError:
        return '--'

def fmt_float(v, decimals=2):
    if v is None: return '--'
    return f'{v:.{decimals}f}'

def fmt_insns(v):
    if v is None: return '--'
    return f'{int(v):,}'

lines = []
lines.append('% AUTO-GENERATED by generate_data.py -- do not edit by hand')
lines.append('% Re-run:  cd task2 && python3 generate_data.py')
lines.append('')

_defined = set()
def defcmd(name, val):
    name = re.sub(r'[^a-zA-Z]', '', name)
    if name in _defined:
        return
    _defined.add(name)
    lines.append(f'\\newcommand{{\\{name}}}{{{val}}}')

SIZE_KEYS = {
    128: 'Ohtwentyeight', 256: 'Twofiftysix', 384: 'Threeeightyfour',
    512: 'Ftwelve', 768: 'Sevensixtyeight',
    1024: 'Ttwentyfour', 1536: 'Fifteenthirtysix',
    2048: 'Tfortyeight', 4096: 'Fninetysix',
}

# ============================================================================
# SIMD width results
# ============================================================================
WIDTH_KEYS = {
    'SSE 128-bit': 'SSE', 'AVX2 256-bit': 'AVX', 'AVX-512 512-bit': 'AVXFiveTwelve',
}

path = os.path.join(BASE, 'bench', 'simd_width_results.txt')
if os.path.exists(path):
    lines.append('')
    lines.append('% === SIMD width speedups, GFLOP/s, instruction counts ===')
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('size') or line.startswith('-'):
                continue
            parts = line.split()
            if len(parts) < 5:
                continue
            size = int(parts[0].split('x')[0])
            if parts[1] == 'naive':
                wkey = 'Naive'
                gflops, speedup_s, insns_s = parts[3], parts[4], parts[5] if len(parts) > 5 else None
            elif parts[1] == 'SSE':
                wkey = 'SSE'
                gflops, speedup_s, insns_s = parts[3], parts[4], parts[5] if len(parts) > 5 else None
            elif parts[1] == 'AVX2':
                wkey = 'AVX'
                gflops, speedup_s, insns_s = parts[3], parts[4], parts[5] if len(parts) > 5 else None
            elif parts[1] == 'AVX-512':
                wkey = 'AVXFiveTwelve'
                gflops, speedup_s, insns_s = parts[3], parts[4], parts[5] if len(parts) > 5 else None
            else:
                continue

            if size in SIZE_KEYS:
                sk = SIZE_KEYS[size]
                defcmd(f'simdWidth{wkey}{sk}Gflops', fmt_float(parse_float(gflops)))
                defcmd(f'simdWidth{wkey}{sk}Speedup', parse_speedup(speedup_s))
                if insns_s:
                    defcmd(f'simdWidth{wkey}{sk}Insns', fmt_insns(parse_float(insns_s)))

# ============================================================================
# Optimized sweep results (SIMD + blocking kernel across sizes)
# ============================================================================
path = os.path.join(BASE, 'bench', 'optimized_sweep_results.txt')
if os.path.exists(path):
    lines.append('')
    lines.append('% === Optimized (SIMD + blocking) sweep ===')
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('size') or line.startswith('='):
                continue
            parts = line.split()
            if len(parts) < 5:
                continue
            size = int(parts[0].split('x')[0])
            if size in SIZE_KEYS:
                sk = SIZE_KEYS[size]
                defcmd(f'optSweep{sk}Gflops', fmt_float(parse_float(parts[3])))
                defcmd(f'optSweep{sk}Speedup', parse_speedup(parts[4]))
                # Hardware counters (new format: insns, L1D, L2, LLC, IPC)
                if len(parts) >= 10:
                    defcmd(f'optSweep{sk}Insns', fmt_insns(parse_float(parts[5])))
                    defcmd(f'optSweep{sk}LoneDmiss', fmt_insns(parse_float(parts[6])))
                    defcmd(f'optSweep{sk}LtwoMiss', fmt_insns(parse_float(parts[7])))
                    defcmd(f'optSweep{sk}LLCmiss', fmt_insns(parse_float(parts[8])))
                    defcmd(f'optSweep{sk}IPC', fmt_float(parse_float(parts[9])))

# ============================================================================
# Perf stage results (hardware counters at 1024)
# ============================================================================
PERF_STAGE_KEYS = {'simd': 'Simd', 'prefetch': 'Prefetch', 'optimized': 'Optimized'}

path = os.path.join(BASE, 'bench', 'perf_stage_results.txt')
if os.path.exists(path):
    lines.append('')
    lines.append('% === Perf counters (M=N=K=1024, cold cache) ===')
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#') or line.startswith('stage'):
                continue
            parts = line.split()
            if len(parts) < 7:
                continue
            stage, cache = parts[0], parts[1]
            if cache != 'cold':
                continue
            if stage in PERF_STAGE_KEYS or stage == 'naive':
                stk = PERF_STAGE_KEYS.get(stage, 'Naive')
                defcmd(f'perf{stk}Insns', fmt_insns(parse_float(parts[2])))
                defcmd(f'perf{stk}LoneDmiss', fmt_insns(parse_float(parts[3])))
                defcmd(f'perf{stk}LtwoMiss', fmt_insns(parse_float(parts[4])))
                defcmd(f'perf{stk}LLCmiss', fmt_insns(parse_float(parts[5])))
                defcmd(f'perf{stk}IPC', fmt_float(parse_float(parts[6])))

# ============================================================================
# Prefetch sweep results
# ============================================================================
MODE_PF_KEYS = {'none': 'None', 'within_row': 'WithinRow', 'next_B': 'NextB',
                'C_output': 'COutput', 'all': 'All'}
HINT_KEYS_PF = {'T0': 'Tzero', 'T1': 'Tone', 'T2': 'Ttwo', 'NTA': 'NTA', '--': 'NA'}
DIST_KEYS = {0: 'Dzero', 16: 'Dsixteen', 32: 'Dthirtytwo', 64: 'Dsixtyfour', 128: 'Donetwentyeight'}

path = os.path.join(BASE, 'bench', 'prefetch_sweep_results.txt')
if os.path.exists(path):
    lines.append('')
    lines.append('% === Prefetch sweep ===')
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('size') or line.startswith('='):
                continue
            parts = line.split()
            if len(parts) < 11:
                continue
            size = int(parts[0].split('x')[0])
            mode, hint, dist_s = parts[1], parts[2], parts[3]
            dist = int(dist_s) if dist_s != '--' else -1

            mk = MODE_PF_KEYS.get(mode)
            hk = HINT_KEYS_PF.get(hint)
            dk = DIST_KEYS.get(dist, f'D{dist}' if dist >= 0 else 'DNA')
            sk = SIZE_KEYS.get(size)
            if not all([mk, hk, sk]):
                continue

            prefix = f'pf{mk}{hk}{dk}{sk}'
            defcmd(f'{prefix}Speedup', parse_speedup(parts[6]))
            defcmd(f'{prefix}Gflops', fmt_float(parse_float(parts[5])))
            defcmd(f'{prefix}NaiveGflops', fmt_float(parse_float(parts[4])))
            defcmd(f'{prefix}LoneDmiss', fmt_insns(parse_float(parts[7])))
            defcmd(f'{prefix}LtwoMiss', fmt_insns(parse_float(parts[8])))
            defcmd(f'{prefix}LLCmiss', fmt_insns(parse_float(parts[9])))
            defcmd(f'{prefix}SwPfAcc', fmt_insns(parse_float(parts[10])))

# ============================================================================
lines.append('')
content = '\n'.join(lines) + '\n'
with open(OUT, 'w') as f:
    f.write(content)
print(f"Written {len(_defined)} macros to {OUT}")
