#!/usr/bin/env python3
r"""Parse *_results.txt and emit task1/report/data.tex with LaTeX macros.

Run from task1/:  python3 generate_data.py
Then compile:     cd report && pdflatex task1_report.tex

Every number in the report that comes from a benchmark is a macro like
  \unrollNaiveKthreeOx{512}   ->  14.00x
so updating numbers = rerunning this script.
"""

import os, re
from collections import defaultdict

BASE = os.path.dirname(os.path.abspath(__file__))
OUT  = os.path.join(BASE, 'report', 'data.tex')

def parse_speedup(s):
    s = s.strip().rstrip('x')
    try:
        v = float(s)
        return f'{v:.2f}x' if v > 0 else '--'
    except ValueError:
        return '--'

def parse_float(s):
    s = s.strip().replace(',', '')
    try:
        v = float(s)
        return v if v != float('inf') else None
    except ValueError:
        return None

def fmt_float(v, decimals=2):
    if v is None:
        return '--'
    return f'{v:.{decimals}f}'

def fmt_insns(v):
    """Format instruction count: raw number -> comma-separated."""
    if v is None:
        return '--'
    n = int(v)
    return f'{n:,}'

def fmt_insns_M(v):
    """Format instruction count in millions."""
    if v is None:
        return '--'
    return f'{v/1e6:,.0f}M'

def safe_cmd(name):
    """Sanitize a string into a valid LaTeX command name (letters only)."""
    return re.sub(r'[^a-zA-Z]', '', name)

lines = []
lines.append('% AUTO-GENERATED by generate_data.py -- do not edit by hand')
lines.append('% Re-run:  cd task1 && python3 generate_data.py')
lines.append('')

SIZE_KEYS = {512: 'Ftwelve', 1024: 'Ttwentyfour', 2048: 'Tfortyeight',
             4096: 'Fninetysix', 8192: 'Eonetwelve'}

K_KEYS = {3: 'Kthree', 5: 'Kfive'}

def defcmd(name, val):
    lines.append(f'\\newcommand{{\\{name}}}{{{val}}}')

# ============================================================================
# UNROLL results
# ============================================================================
STRAT_KEYS = {
    'unroll_ox': 'UnrollOx', 'unroll_kx': 'UnrollKx',
    'unroll_ky': 'UnrollKy', 'unroll_ox_oy': 'UnrollOxOy',
    'reord_unroll_ox': 'ReordOx', 'reord_unroll_oy': 'ReordOy',
    'reord_unroll_ox_oy': 'ReordOxOy', 'reord_unroll_kx': 'ReordKx',
}

path = os.path.join(BASE, 'unroll_results.txt')
if os.path.exists(path):
    lines.append('')
    lines.append('% === Unroll speedups ===')
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('HxW') or line.startswith('='):
                continue
            parts = line.split()
            if len(parts) < 8:
                continue
            size = int(parts[0].split('x')[0])
            K = int(parts[1])
            strat = parts[2]
            speedup = parse_speedup(parts[7])
            if strat in STRAT_KEYS and size in SIZE_KEYS and K in K_KEYS:
                cmd = f'unroll{STRAT_KEYS[strat]}{K_KEYS[K]}{SIZE_KEYS[size]}'
                defcmd(cmd, speedup)

# ============================================================================
# REORDER results
# ============================================================================
path = os.path.join(BASE, 'reorder_results.txt')
if os.path.exists(path):
    lines.append('')
    lines.append('% === Reorder speedups ===')
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('HxW') or line.startswith('='):
                continue
            parts = line.split()
            if len(parts) < 7:
                continue
            size = int(parts[0].split('x')[0])
            K = int(parts[1])
            speedup = parse_speedup(parts[6])
            if size in SIZE_KEYS and K in K_KEYS:
                defcmd(f'reorder{K_KEYS[K]}{SIZE_KEYS[size]}', speedup)

# ============================================================================
# TILE results
# ============================================================================
TILE_KEYS = {8: 'Eight', 16: 'Sixteen', 32: 'Thirtytwo', 64: 'Sixtyfour',
             128: 'Onetwentyeight', 256: 'Twofiftysix'}

path = os.path.join(BASE, 'tile_results.txt')
if os.path.exists(path):
    lines.append('')
    lines.append('% === Tile speedups and MPKI ===')
    naive_mpki_written = set()
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('HxW') or line.startswith('='):
                continue
            parts = line.split()
            if len(parts) < 10:
                continue
            size = int(parts[0].split('x')[0])
            K = int(parts[1])
            tile_h = int(parts[2])
            speedup = parse_speedup(parts[7])
            naive_mpki = parse_float(parts[8])
            tile_mpki = parse_float(parts[9])

            if size in SIZE_KEYS and K in K_KEYS and tile_h in TILE_KEYS:
                prefix = f'tile{TILE_KEYS[tile_h]}{K_KEYS[K]}{SIZE_KEYS[size]}'
                defcmd(f'{prefix}Speedup', speedup)
                defcmd(f'{prefix}MPKI', fmt_float(tile_mpki))

                key = (K, size)
                if key not in naive_mpki_written and naive_mpki is not None:
                    defcmd(f'naiveMPKI{K_KEYS[K]}{SIZE_KEYS[size]}', fmt_float(naive_mpki))
                    naive_mpki_written.add(key)

# ============================================================================
# SIMD results
# ============================================================================
WIDTH_KEYS = {'SSE_128': 'SSE', 'AVX2_256': 'AVX'}

path = os.path.join(BASE, 'simd_results.txt')
if os.path.exists(path):
    lines.append('')
    lines.append('% === SIMD speedups, instruction counts ===')
    naive_insns_written = set()
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('HxW') or line.startswith('='):
                continue
            parts = line.split()
            if len(parts) < 10:
                continue
            size = int(parts[0].split('x')[0])
            K = int(parts[1])
            width = parts[2]
            speedup = parse_speedup(parts[7])
            naive_insns = parse_float(parts[8])
            simd_insns = parse_float(parts[9])

            if size in SIZE_KEYS and K in K_KEYS and width in WIDTH_KEYS:
                prefix = f'simd{WIDTH_KEYS[width]}{K_KEYS[K]}{SIZE_KEYS[size]}'
                defcmd(f'{prefix}Speedup', speedup)
                defcmd(f'{prefix}Insns', fmt_insns_M(simd_insns))

                key = (K, size)
                if key not in naive_insns_written and naive_insns is not None:
                    defcmd(f'naiveInsns{K_KEYS[K]}{SIZE_KEYS[size]}', fmt_insns_M(naive_insns))
                    naive_insns_written.add(key)

# ============================================================================
# OPTIMIZED results
# ============================================================================
path = os.path.join(BASE, 'optimized_results.txt')
if os.path.exists(path):
    lines.append('')
    lines.append('% === Optimized speedups ===')
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('HxW') or line.startswith('='):
                continue
            parts = line.split()
            if len(parts) < 7:
                continue
            size = int(parts[0].split('x')[0])
            K = int(parts[1])
            speedup = parse_speedup(parts[6])
            if size in SIZE_KEYS and K in K_KEYS:
                defcmd(f'optimized{K_KEYS[K]}{SIZE_KEYS[size]}', speedup)

lines.append('')

with open(OUT, 'w') as f:
    f.write('\n'.join(lines) + '\n')

print(f'Written {len([l for l in lines if l.startswith(chr(92))])} macros to {OUT}')
